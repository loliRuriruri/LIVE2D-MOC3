# Portable release packaging for Live2DRecovery (AGENT.5.3).
#
# Requires: cargo, python (only for generating synthetic canvas-sized PNGs).
# Produces dist/Live2DRecovery-<version>-win-x64/ plus a zip.
param(
    [string]$Version = "0.1.0-alpha"
)

$ErrorActionPreference = "Stop"
$root = Resolve-Path (Join-Path $PSScriptRoot "..\..")
$distRoot = Join-Path $root "dist"
$package = Join-Path $distRoot "Live2DRecovery-$Version-win-x64"
$acceptance = Join-Path $package "acceptance"
$samples = Join-Path $package "samples"
$licenses = Join-Path $package "LICENSES"

if (Test-Path $package) { Remove-Item -Recurse -Force $package }
New-Item -ItemType Directory -Force -Path $package, $acceptance, $samples, $licenses | Out-Null

Write-Output "building release binary..."
Push-Location $root
try {
    cargo build --release -p recovery-cli | Out-Host
} finally {
    Pop-Location
}
$exe = Join-Path $root "target\release\recovery.exe"
$distExe = Join-Path $package "Live2DRecovery.exe"
Copy-Item $exe $distExe

# Synthetic canvas-sized PNG generator (no third-party assets are used).
$pngScript = Join-Path $env:TEMP "l2d-package-png.py"
@'
import struct, sys, zlib
def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
def solid(width, height, rgba):
    raw = b"".join(b"\x00" + bytes(rgba) * width for _ in range(height))
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 1)) + chunk(b"IEND", b"")
open(sys.argv[3], "wb").write(solid(int(sys.argv[1]), int(sys.argv[2]), (90, 150, 210, 255)))
'@ | Set-Content -Encoding UTF8 $pngScript

$cases = @(
    @{ Name = "01-minimal"; Fixture = "fixture-002-artmesh-param.moc3"; Note = "1 Part + 1 ArtMesh + 1 texture + 2-key parameter" },
    @{ Name = "02-deformer"; Fixture = "hierarchy-005-warp-rotation-artmesh.moc3"; Note = "Part -> Warp -> Rotation -> ArtMesh" },
    @{ Name = "03-keyform"; Fixture = "keyform-002-1d-three-keys.moc3"; Note = "1 parameter with 3 keys and keyed part/art-mesh forms" }
)

foreach ($case in $cases) {
    $sampleDir = Join-Path $samples $case.Name
    New-Item -ItemType Directory -Force -Path (Join-Path $sampleDir "textures") | Out-Null
    $fixture = Join-Path $root "fixtures\synthetic\$($case.Fixture)"
    Copy-Item $fixture (Join-Path $sampleDir "model.moc3")
    & python $pngScript 800 600 (Join-Path $sampleDir "textures\page0.png") | Out-Null
    @"
Live2DRecovery synthetic sample: $($case.Name)
$($case.Note)

Run:
  Live2DRecovery.exe recover model.moc3 --textures textures --output recovered.cmo3

Generated by the project itself; no third-party model data is included.
"@ | Set-Content -Encoding UTF8 (Join-Path $sampleDir "README.txt")

    $cmo3 = Join-Path $acceptance "$($case.Name).cmo3"
    & $distExe recover $fixture --textures (Join-Path $sampleDir "textures") --output $cmo3 --report (Join-Path $acceptance "$($case.Name).report.json") | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "recover failed for $($case.Name)" }

    $precheck = & $distExe inspect-cmo3 $cmo3 --json | ConvertFrom-Json
    if (-not $precheck.caff.valid -or $precheck.xml.dangling_refs -ne 0 -or $precheck.xml.duplicate_ids -ne 0) {
        throw "structural precheck failed for $($case.Name)"
    }
    $expected = Join-Path $acceptance "expected"
    New-Item -ItemType Directory -Force -Path $expected | Out-Null
    $precheck | ConvertTo-Json -Depth 6 | Set-Content -Encoding UTF8 (Join-Path $expected "$($case.Name).inspection.json")
    Write-Output "acceptance $($case.Name): structural PASS"
}

@'
