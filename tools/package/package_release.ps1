$hashLines = @()
$hashLines += "SHA256 Live2DRecovery.exe  $((Get-FileHash $distExe -Algorithm SHA256).Hash.ToLower())"
foreach ($case in $cases) {
    $cmo3 = Join-Path $acceptance "$($case.Name).cmo3"
    $hashLines += "SHA256 acceptance/$($case.Name).cmo3  $((Get-FileHash $cmo3 -Algorithm SHA256).Hash.ToLower())"
}
$hashLines | Set-Content -Encoding ASCII (Join-Path $package "checksums.txt")

$zip = Join-Path $distRoot "Live2DRecovery-$Version-win-x64.zip"
if (Test-Path $zip) { Remove-Item -Force $zip }
Compress-Archive -Path $package -DestinationPath $zip
Write-Output "package: $package"
Write-Output "zip:     $zip"
Get-Content (Join-Path $package "checksums.txt")
