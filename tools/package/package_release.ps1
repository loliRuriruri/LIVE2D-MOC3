see expected/*.inspection.json.

## 01-minimal.cmo3
[ ] opens without repair/recovery dialog
[ ] texture visible, correct orientation, not black
[ ] art mesh visible
[ ] no fatal warnings

## 02-deformer.cmo3
[ ] opens; Part -> Warp -> Rotation -> ArtMesh hierarchy visible
[ ] geometry visible under the deformers

## 03-keyform.cmo3
[ ] opens; parameter visible with 3 keys
[ ] moving the parameter moves the keyed forms (min/default/max)

## Save/reopen (each file)
[ ] Save As -> Close -> Reopen the saved file succeeds

Record exact editor version, OS and date here when executed.
Structural PASS is NOT a Cubism compatibility claim.
'@ | Set-Content -Encoding UTF8 (Join-Path $acceptance "ACCEPTANCE_CHECKLIST.md")

@'
